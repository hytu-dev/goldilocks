"""Builds the Goldilocks space font and writes it to src/space/data.ts.

    uv run gen/font.py

The font maps U+0020 and U+00A0 to one empty glyph with zero advance: the width of a space is left
to CSS word-spacing, and the font exists only so that spaces fall in a shaping run of their own.

Its vertical metrics are ordinary ones (ascent + descent = 1em), not zero: Chromium paints no text
decoration over a fragment whose font has zero ascent and descent. The inline box is flattened by
line-height: 0 instead, to a point (ASCENT - DESCENT) / 2 above the baseline, near the middle of a
typical Latin font's content area.

fontTools is pinned so that the output, and with it the family name, is reproducible.
"""

import base64
import hashlib
import io
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

OUTPUT = Path(__file__).parent.parent / "src" / "space" / "data.ts"

UPEM = 1000
ASCENT = 800
DESCENT = 200
UNDERLINE_POSITION = -100
UNDERLINE_THICKNESS = 50
TIMESTAMP = 0  # fixed, so that the output is reproducible
NAME = "Goldilocks Space"


def notdef():
    pen = TTGlyphPen(None)
    for contour in [[(50, 0), (50, 700), (450, 700), (450, 0)], [(100, 50), (400, 50), (400, 650), (100, 650)]]:
        pen.moveTo(contour[0])
        for point in contour[1:]:
            pen.lineTo(point)
        pen.closePath()
    return pen.glyph()


def build() -> bytes:
    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder([".notdef", "space"])
    fb.setupCharacterMap({0x20: "space", 0xA0: "space"})
    fb.setupGlyf({".notdef": notdef(), "space": TTGlyphPen(None).glyph()})
    fb.setupHorizontalMetrics({".notdef": (500, 50), "space": (0, 0)})
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT, lineGap=0)
    fb.setupNameTable({"familyName": NAME, "styleName": "Regular"})
    fb.setupOS2(
        version=4,
        sTypoAscender=ASCENT,
        sTypoDescender=-DESCENT,
        sTypoLineGap=0,
        usWinAscent=ASCENT,
        usWinDescent=DESCENT,
        fsSelection=0x00C0,  # REGULAR, USE_TYPO_METRICS
        achVendID="GOLD",
    )
    fb.setupPost(keepGlyphNames=False, underlinePosition=UNDERLINE_POSITION, underlineThickness=UNDERLINE_THICKNESS)
    fb.updateHead(created=TIMESTAMP, modified=TIMESTAMP)
    fb.font.recalcTimestamp = False
    buffer = io.BytesIO()
    fb.save(buffer)
    return buffer.getvalue()


def main() -> None:
    font = build()
    digest = hashlib.sha256(font).hexdigest()[:8]
    data = base64.b64encode(font).decode("ascii")
    OUTPUT.write_text(
        "// generated by gen/font.py; do not edit by hand, run `uv run gen/font.py` instead\n"
        "\n"
        f'export const FAMILY = "goldilocks-space-{digest}";\n'
        "\n"
        "export const DATA =\n"
        f'  "{data}";\n'
    )


if __name__ == "__main__":
    main()
